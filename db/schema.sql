-- KashNode PostgreSQL schema. Safe to run more than once.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user',
  name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS name TEXT;
ALTER TABLE public.users ALTER COLUMN role SET DEFAULT 'user';

-- These definitions match the live Supabase tables (including nullable columns).
CREATE TABLE IF NOT EXISTS public.merchants (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name VARCHAR(255) NOT NULL,
  webhook_secret VARCHAR(255) NOT NULL,
  shopify_domain VARCHAR(255),
  shopify_webhook_secret TEXT,
  ai_voice_rules JSONB NOT NULL DEFAULT '[]'::jsonb,
  wallet_balance NUMERIC(12,2) DEFAULT 0.00,
  created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE public.merchants
  ADD COLUMN IF NOT EXISTS shopify_domain VARCHAR(255),
  ADD COLUMN IF NOT EXISTS shopify_webhook_secret TEXT,
  ADD COLUMN IF NOT EXISTS ai_voice_rules JSONB NOT NULL DEFAULT '[]'::jsonb;

CREATE TABLE IF NOT EXISTS public.orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  merchant_id UUID NOT NULL REFERENCES public.merchants(id) ON DELETE CASCADE,
  platform_order_id VARCHAR(100) NOT NULL,
  customer_phone VARCHAR(20) NOT NULL,
  customer_name VARCHAR(255),
  total_amount NUMERIC(10,2) NOT NULL,
  payment_status VARCHAR(50) DEFAULT 'unpaid',
  delivery_status VARCHAR(50) DEFAULT 'pending',
  payment_method TEXT,
  customer_trx_id TEXT,
  line_items JSONB NOT NULL DEFAULT '[]'::jsonb,
  is_phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
  ai_call_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  financial_status VARCHAR(50),
  currency VARCHAR(3),
  created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE public.orders
  ADD COLUMN IF NOT EXISTS customer_phone VARCHAR(20),
  ADD COLUMN IF NOT EXISTS payment_method TEXT,
  ADD COLUMN IF NOT EXISTS customer_trx_id TEXT,
  ADD COLUMN IF NOT EXISTS line_items JSONB NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS is_phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS ai_call_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  ADD COLUMN IF NOT EXISTS financial_status VARCHAR(50),
  ADD COLUMN IF NOT EXISTS currency VARCHAR(3);

CREATE UNIQUE INDEX IF NOT EXISTS orders_merchant_platform_order_uidx
  ON public.orders (merchant_id, platform_order_id);

CREATE TABLE IF NOT EXISTS public.raw_sms_inbox (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  merchant_id UUID REFERENCES public.merchants(id) ON DELETE CASCADE,
  sender_number VARCHAR(50) NOT NULL,
  raw_message TEXT NOT NULL,
  parsed_trxid VARCHAR(100),
  parsed_amount NUMERIC(10,2),
  is_reconciled BOOLEAN DEFAULT FALSE,
  received_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.device_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id TEXT NOT NULL,
  balance_bdt NUMERIC(12,2) NOT NULL DEFAULT 0,
  data_mb NUMERIC(12,2) NOT NULL DEFAULT 0,
  signal_strength NUMERIC(3,1),
  raw_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE public.device_logs ADD COLUMN IF NOT EXISTS raw_payload JSONB NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE public.device_logs ADD COLUMN IF NOT EXISTS is_online BOOLEAN NOT NULL DEFAULT TRUE;
DO $$ BEGIN
  IF (SELECT data_type FROM information_schema.columns WHERE table_schema='public' AND table_name='device_logs' AND column_name='signal_strength') = 'character varying' THEN
    ALTER TABLE public.device_logs ALTER COLUMN signal_strength TYPE NUMERIC(3,1) USING NULLIF(signal_strength, '')::numeric;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS device_logs_created_at_idx ON public.device_logs (created_at DESC);

CREATE TABLE IF NOT EXISTS public.transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gateway TEXT NOT NULL CHECK (gateway IN ('bKash','Nagad','Rocket','Upay')),
  trx_id TEXT NOT NULL UNIQUE,
  sender_phone TEXT,
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  reference_user_id TEXT,
  status TEXT NOT NULL DEFAULT 'unmatched' CHECK (status IN ('matched','unmatched')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.ai_calls (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone_number TEXT NOT NULL,
  duration INTEGER,
  recording_url TEXT,
  ai_summary TEXT,
  status TEXT NOT NULL DEFAULT 'Completed',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
DO $$ BEGIN
  IF (SELECT data_type FROM information_schema.columns WHERE table_schema='public' AND table_name='ai_calls' AND column_name='duration') IN ('character varying','text') THEN
    ALTER TABLE public.ai_calls ALTER COLUMN duration TYPE INTEGER USING CASE WHEN duration ~ '^[0-9]+$' THEN duration::integer ELSE NULL END;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS ai_calls_created_at_idx ON public.ai_calls (created_at DESC);

CREATE TABLE IF NOT EXISTS public.courier_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code TEXT NOT NULL,
  courier_name TEXT NOT NULL CHECK (courier_name IN ('Steadfast','RedX','Pathao')),
  tracking_code TEXT,
  status TEXT NOT NULL DEFAULT 'Processing',
  delivery_charge NUMERIC(12,2),
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='courier_orders' AND column_name='delivery_status')
    AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='courier_orders' AND column_name='status') THEN
    ALTER TABLE public.courier_orders RENAME COLUMN delivery_status TO status;
  END IF;
END $$;
ALTER TABLE public.courier_orders ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'Processing';
ALTER TABLE public.courier_orders ADD COLUMN IF NOT EXISTS recipient_name TEXT;
ALTER TABLE public.courier_orders ADD COLUMN IF NOT EXISTS recipient_phone TEXT;
CREATE INDEX IF NOT EXISTS courier_orders_codes_idx ON public.courier_orders (order_code, tracking_code);

CREATE TABLE IF NOT EXISTS public.ussd_settings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  frequency TEXT NOT NULL DEFAULT 'Every 6 hours',
  balance_code TEXT NOT NULL DEFAULT '*566#',
  data_code TEXT NOT NULL DEFAULT '*5000#',
  auto_balance BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE public.ussd_settings ADD COLUMN IF NOT EXISTS auto_balance BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE public.ussd_settings ALTER COLUMN id SET DEFAULT 1;

-- B2B SaaS merchant identity, plan quotas, and signup verification.
ALTER TABLE public.users ALTER COLUMN password_hash DROP NOT NULL;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS google_sub TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS users_google_sub_uidx ON public.users (google_sub) WHERE google_sub IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_uidx ON public.users (lower(email));

ALTER TABLE public.merchants
  ADD COLUMN IF NOT EXISTS subscription_plan VARCHAR(32) NOT NULL DEFAULT 'free',
  ADD COLUMN IF NOT EXISTS available_orders INTEGER NOT NULL DEFAULT 10,
  ADD COLUMN IF NOT EXISTS available_voice_minutes INTEGER NOT NULL DEFAULT 10,
  ADD COLUMN IF NOT EXISTS overage_rate_per_min NUMERIC(10,2) NOT NULL DEFAULT 7.00,
  ADD COLUMN IF NOT EXISTS email VARCHAR(254),
  ADD COLUMN IF NOT EXISTS owner_user_id UUID;
ALTER TABLE public.merchants ALTER COLUMN webhook_secret SET DEFAULT encode(gen_random_bytes(32), 'hex');

DO $merchants$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'merchants_owner_user_id_fkey' AND conrelid = 'public.merchants'::regclass) THEN
    ALTER TABLE public.merchants ADD CONSTRAINT merchants_owner_user_id_fkey FOREIGN KEY (owner_user_id) REFERENCES public.users(id) ON DELETE SET NULL;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'merchants_available_orders_nonnegative_check' AND conrelid = 'public.merchants'::regclass) THEN
    ALTER TABLE public.merchants ADD CONSTRAINT merchants_available_orders_nonnegative_check CHECK (available_orders >= 0);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'merchants_available_voice_minutes_nonnegative_check' AND conrelid = 'public.merchants'::regclass) THEN
    ALTER TABLE public.merchants ADD CONSTRAINT merchants_available_voice_minutes_nonnegative_check CHECK (available_voice_minutes >= 0);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'merchants_overage_rate_nonnegative_check' AND conrelid = 'public.merchants'::regclass) THEN
    ALTER TABLE public.merchants ADD CONSTRAINT merchants_overage_rate_nonnegative_check CHECK (overage_rate_per_min >= 0);
  END IF;
END
$merchants$;

CREATE UNIQUE INDEX IF NOT EXISTS merchants_webhook_secret_uidx ON public.merchants (webhook_secret);
CREATE UNIQUE INDEX IF NOT EXISTS merchants_shopify_domain_uidx ON public.merchants (lower(shopify_domain)) WHERE shopify_domain IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS merchants_owner_user_uidx ON public.merchants (owner_user_id) WHERE owner_user_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS merchants_email_lower_uidx ON public.merchants (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.merchant_signup_otps (
  email VARCHAR(254) PRIMARY KEY,
  name VARCHAR(80) NOT NULL,
  password_hash TEXT NOT NULL,
  otp_hash CHAR(64) NOT NULL,
  attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS merchant_signup_otps_expires_idx ON public.merchant_signup_otps (expires_at);

